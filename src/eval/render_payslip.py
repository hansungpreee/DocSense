def floor10(x: float) -> int:
    return int(x) // 10 * 10


def income_tax(taxable: int) -> int:
    """과세 급여에 구간 비율을 곱한 근사값 (실제 간이세액표 아님)."""
    for limit, rate in [(1_800_000, 0.0), (2_500_000, 0.008), (3_500_000, 0.02), (4_500_000, 0.035), (6_000_000, 0.05)]:
        if taxable < limit:
            return floor10(taxable * rate)
    return floor10(taxable * 0.065)


def pay(item, formula, amount, nontax=False, excl=False, unit=None, qty=None):
    """excl=True: 보험·소득세 계산에서 뺀다 (연말정산 환급금처럼 근로소득이 아닌 지급)."""
    return {"항목": item, "산식": formula, "금액": amount, "비과세": nontax, "제외": excl, "단가": unit, "수량": qty}


def build(spec: dict) -> dict:
    pays = spec["지급"]
    base = sum(p["금액"] for p in pays if not p["비과세"] and not p["제외"])
    health = floor10(base * HEALTH)
    nps_base = min(base, NPS_CAP)
    nps_text = f"기준소득월액 {nps_base:,} × 4.5%" + (" (상한 적용)" if base > NPS_CAP else "")
    tax = income_tax(base)
    deducts = [
        {"항목": "국민연금", "산식": nps_text, "금액": floor10(nps_base * NPS)},
        {"항목": "건강보험", "산식": f"보수월액 {base:,} × 3.595%", "금액": health},
        {"항목": "장기요양보험", "산식": "건강보험료 × 13.14%", "금액": floor10(health * LTC)},
        {"항목": "고용보험", "산식": f"{base:,} × 0.9%", "금액": floor10(base * EMP)},
        {"항목": "소득세", "산식": "간이세액 적용", "금액": tax},
        {"항목": "지방소득세", "산식": "소득세 × 10%", "금액": floor10(tax * 0.1)},
    ] + [{"항목": n, "산식": f, "금액": a} for n, f, a in spec.get("기타공제", [])]
    gross, cut = sum(p["금액"] for p in pays), sum(d["금액"] for d in deducts)
    return {
        "문서ID": spec["문서ID"], "layout": spec["layout"], "제목": spec["제목"], "회사명": COMPANY,
        "귀속월": spec["귀속월"], "지급일": spec["지급일"], "인적": spec["인적"], "근태": spec.get("근태", []),
        "지급": pays, "공제": deducts, "지급합계": gross, "공제합계": cut, "실수령액": gross - cut,
        "입금계좌": spec["입금계좌"], "비고": spec["비고"],
    }


